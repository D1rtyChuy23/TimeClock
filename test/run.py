"""Drives index.html in headless Chromium against fake-supabase.js and checks every state machine.
Run: python3 test/run.py   (needs: pip install playwright)"""
import asyncio, os, sys
from playwright.async_api import async_playwright
HERE=os.path.dirname(os.path.abspath(__file__))
HTML=open(os.path.join(HERE,"..","index.html")).read()
FAKE=open(os.path.join(HERE,"fake-supabase.js")).read()
URL="http://app.test/index.html"
fails=[]; n=0
def check(name,cond,detail=""):
    global n; n+=1
    print(("  ok   " if cond else "  FAIL ")+name+(("  -> "+str(detail)) if not cond else ""))
    if not cond: fails.append(name)

async def main():
    async with async_playwright() as p:
        b=await p.chromium.launch(); pg=await b.new_page(viewport={"width":400,"height":900})
        errs=[]
        pg.on("pageerror",lambda e:errs.append("pageerror: "+str(e)))
        pg.on("console",lambda m:errs.append("console: "+m.text) if m.type=="error" else None)
        async def route(r):
            u=r.request.url
            if u==URL: await r.fulfill(body=HTML,content_type="text/html")
            elif "supabase-js" in u: await r.fulfill(body=FAKE,content_type="application/javascript")
            else: await r.fulfill(body="",content_type="text/css")  # fonts: not needed for the test
        await pg.route("**/*",route)
        st=lambda k: pg.evaluate("k=>document.body.dataset[k]",k)
        vis=pg.is_visible; txt=pg.text_content
        settle=lambda ms=250: pg.wait_for_timeout(ms)
        async def state(k,v,ms=3000):
            try: await pg.wait_for_function("([k,v])=>document.body.dataset[k]===v",arg=[k,v],timeout=ms); return True
            except Exception: return False
        async def signup(name,email,pw="password1"):
            await pg.click("#sw-signup"); await pg.fill("#a-name",name); await pg.fill("#a-email",email); await pg.fill("#a-pass",pw); await pg.click("#a-submit")
        async def signin(email,pw="password1"):
            await pg.fill("#a-email",email); await pg.fill("#a-pass",pw); await pg.click("#a-submit")
        async def signout():
            await pg.click("#btn-out"); await state("session","signedOut")

        print("session + auth form")
        await pg.goto(URL)
        check("boots to signedOut",await state("session","signedOut"))
        check("sign-in form shown, app hidden",await vis("#v-auth") and not await vis("#v-clock") and not await vis("#msg"))
        await pg.click("#sw-signup"); check("auth -> signup",await st("auth")=="signup" and await vis("#lbl-name"))
        await pg.click("#sw-signin"); check("auth -> signin",await st("auth")=="signin" and not await vis("#lbl-name"))
        await pg.click("#sw-reset"); check("auth -> reset",await st("auth")=="reset" and not await vis("#lbl-pass"))
        await pg.fill("#a-email","x@y.z"); await pg.click("#a-submit"); await settle()
        check("reset sent -> back on sign-in with note",await st("auth")=="signin" and "reset link" in await txt("#a-note"))
        await signin("nobody@y.z"); await settle()
        check("wrong password says so",(await txt("#a-note")).startswith("Email or password is wrong"))
        await pg.evaluate("__fake.setFail(true)"); await pg.click("#a-submit"); await settle()
        check("server down is not blamed on the password",(await txt("#a-note")).startswith("Can't reach the time clock"))
        await pg.evaluate("__fake.setFail(false)")
        await pg.evaluate("__fake.cfg.confirmEmail=true"); await signup("Wait Er","wait@y.z"); await settle()
        check("sign-up needing email confirm -> sign-in form + note",await st("auth")=="signin" and "Check your email" in await txt("#a-note") and await st("session")=="signedOut")
        await pg.click("#a-submit"); await settle()
        check("unconfirmed sign-in explains",(await txt("#a-note")).startswith("Confirm your email first"))
        await pg.evaluate("__fake.cfg.confirmEmail=false; __fake.st.users.length=0; __fake.st.profiles.length=0; __fake.save()")

        print("first account, clock machine")
        await signup("Ana Admin","ana@y.z")
        check("first sign-up -> ready",await state("session","ready"))
        check("first account is admin, tabs shown",await st("role")=="admin" and await vis("#tabs"))
        check("starts clocked out",await st("shift")=="out" and (await txt("#btn-punch"))=="Clock in")
        await pg.evaluate("__fake.cfg.calls.length=0; __fake.cfg.delay=150")
        await pg.click("#btn-punch"); await pg.click("#btn-punch",force=True); await pg.evaluate("document.getElementById('btn-punch').click()")
        check("clock in",await state("shift","in") and (await txt("#btn-punch"))=="Clock out")
        await state("busy","idle")
        calls=await pg.evaluate("__fake.cfg.calls.filter(c=>c.startsWith('rpc'))")
        check("triple tap sends one clock-in",calls==["rpc.clock.in"],calls)
        await pg.evaluate("__fake.cfg.delay=30")
        await pg.click("#btn-punch"); check("clock out",await state("shift","out"))
        await state("busy","idle")
        check("shift appears in history",await pg.locator("#hist li").count()==1)
        # another device clocked in; this screen is stale and still offers "Clock in"
        await pg.evaluate("__fake.st.punches.push({id:999,user_id:__fake.st.session.user.id,clock_in:new Date().toISOString(),clock_out:null,manual:false}); __fake.save()")
        check("stale screen still says Clock in",(await txt("#btn-punch"))=="Clock in")
        await pg.click("#btn-punch"); await state("shift","in"); await state("busy","idle")
        opens=await pg.evaluate("__fake.st.punches.filter(p=>!p.clock_out).length")
        check("stale Clock in does not flip to out",await st("shift")=="in" and opens==1 and "already clocked in" in await txt("#toast"),(opens,await txt("#toast")))
        await pg.click("#btn-punch"); await state("shift","out"); await state("busy","idle")

        print("time off (employee side), busy lock")
        await pg.fill("#pto-date","2026-12-24"); await pg.evaluate("__fake.cfg.delay=150")
        await pg.click("#f-pto button"); await pg.evaluate("document.getElementById('f-pto').requestSubmit()")
        await state("busy","saving"); await state("busy","idle")
        await pg.evaluate("__fake.cfg.delay=30")
        check("double submit creates one request",await pg.evaluate("__fake.st.pto_requests.length")==1)
        check("pending request offers Cancel only",await pg.locator("#pto-list [data-act=ptocancel]").count()==1 and await pg.locator("#pto-list [data-act=ptoset]").count()==0)
        await pg.click("#pto-list [data-act=ptocancel]"); await settle(400)
        check("cancel removes it",await pg.evaluate("__fake.st.pto_requests.length")==0)

        print("holiday + delete confirm")
        await pg.fill("#hol-date","2099-12-25"); await pg.fill("#hol-name","Navidad"); await pg.click("#f-hol button"); await settle(400)
        check("holiday added, notice shown",await pg.locator("#hol-list li").count()==1 and await vis("#hol-notice"))
        await pg.click("#hol-list [data-act=delhol]"); await settle(100)
        check("first tap arms delete",(await txt("#hol-list [data-act=delhol]"))=="Tap again" and await pg.evaluate("__fake.st.holidays.length")==1)
        await pg.evaluate("window.dispatchEvent(new Event('online'))"); await settle(300)
        check("armed survives a background refresh",(await txt("#hol-list [data-act=delhol]"))=="Tap again")
        await pg.wait_for_timeout(3100)
        check("arming times out",(await txt("#hol-list [data-act=delhol]"))=="Delete" and await pg.evaluate("__fake.st.holidays.length")==1)
        await pg.click("#hol-list [data-act=delhol]"); await settle(100); await pg.click("#hol-list [data-act=delhol]"); await settle(400)
        check("second tap deletes",await pg.evaluate("__fake.st.holidays.length")==0)

        print("employee account")
        await signout()
        check("sign out clears data",await pg.evaluate("Object.keys(timeclock.state).length")==5 and not await vis("#v-clock") and await st("role")=="")
        await signup("Beto Emp","beto@y.z"); await state("session","ready")
        check("second account is employee, no tabs",await st("role")=="employee" and not await vis("#tabs") and not await vis("#f-hol"))
        await pg.click("#btn-punch"); await state("shift","in"); await state("busy","idle")
        await pg.fill("#pto-date","2026-12-26"); await pg.click("#f-pto button"); await settle(400)
        await signout()

        print("admin: nav machine, time-off machine, force clock-out")
        await signin("ana@y.z"); await state("session","ready")
        await pg.click("#tabs [data-v=team]"); check("nav -> team",await st("nav")=="team" and await vis("#team-list") and not await vis("#v-clock"))
        check("team shows 2 people, Beto in, 1 waiting",await pg.locator("#team-list li").count()==2 and "1 waiting" in await txt("#team-list"))
        await pg.click("#team-list li:has-text('Beto')"); check("nav -> person",await st("nav")=="person" and (await txt("#d-name"))=="Beto Emp")
        check("pending offers Approve + Deny",await pg.locator("#d-pto [data-s=approved]").count()==1 and await pg.locator("#d-pto [data-s=denied]").count()==1)
        await pg.click("#d-pto [data-s=approved]"); await settle(400)
        check("approved, offers Undo only",(await txt("#d-pto .pill"))=="Approved" and (await txt("#d-pto .row-btns"))=="Undo")
        await pg.click("#d-pto [data-s=pending]"); await settle(400)
        check("undo -> pending again",(await txt("#d-pto .pill"))=="Pending" and await pg.evaluate("__fake.st.pto_requests[0].decided_by")==None)
        await pg.click("#d-pto [data-s=denied]"); await settle(400)
        check("denied",(await txt("#d-pto .pill"))=="Denied")
        await pg.click("[data-act=forceout]"); await settle(400)
        check("force clock-out",await pg.evaluate("__fake.st.punches.filter(p=>!p.clock_out).length")==0 and await pg.locator("[data-act=forceout]").count()==0)
        await pg.fill("#allow","80"); await pg.click("#f-allow button"); await settle(400)
        check("allowance saved",await pg.evaluate("__fake.st.profiles.find(p=>p.email==='beto@y.z').pto_allowance")==80)
        await pg.fill("#sh-in","22:00"); await pg.fill("#sh-out","06:00"); await pg.click("#f-shift button"); await settle(400)
        check("overnight missed shift added (8.00 h)","8.00" in await txt("#d-shifts"))
        before=await pg.locator("#d-shifts li").count()
        await pg.click("#d-shifts [data-act=delpunch] >> nth=0"); await settle(100); await pg.click("#d-shifts .armed"); await settle(400)
        check("shift delete with two taps",await pg.locator("#d-shifts li").count()==before-1)
        await pg.click("[data-act=role]"); await settle(400)
        check("promote to admin",await pg.evaluate("__fake.st.profiles.find(p=>p.email==='beto@y.z').role")=="admin")
        await pg.click("[data-act=role]"); await settle(400)
        await pg.click("[data-act=back]"); check("nav person -> team",await st("nav")=="team")
        await pg.click("#team-list li:has-text('Beto')"); await pg.click("#tabs [data-v=clock]"); check("nav person -> clock",await st("nav")=="clock" and await vis("#v-clock"))

        print("sync machine, load error, demotion")
        await pg.evaluate("__fake.setFail(true); window.dispatchEvent(new Event('online'))")
        check("failed refresh -> stale notice, data kept",await state("sync","stale") and await vis("#sync-notice") and await vis("#btn-punch"))
        await pg.click("#btn-punch"); await settle(400)
        check("save while offline reports failure",(await txt("#toast")).startswith("That didn't save") and await st("busy")=="idle")
        await pg.reload()
        check("first load failing -> loadError with retry",await state("session","loadError") and await vis("#v-error") and not await vis("#v-clock"))
        await pg.evaluate("__fake.setFail(false)"); await pg.click("[data-act=retry]")
        check("retry -> ready",await state("session","ready") and await st("sync")=="ok" and not await vis("#sync-notice"))
        await pg.click("#tabs [data-v=team]"); await pg.click("#team-list li:has-text('Beto')")
        await pg.evaluate("__fake.st.profiles.find(p=>p.email==='ana@y.z').role='employee'; __fake.save(); window.dispatchEvent(new Event('online'))")
        check("demoted while on Team -> back to own clock",await state("nav","clock") and await state("role","employee") and not await vis("#tabs"))
        await pg.evaluate("__fake.st.profiles.find(p=>p.email==='ana@y.z').role='admin'; __fake.save()")

        print("password recovery, reload, language")
        await pg.evaluate("__fake.emit('PASSWORD_RECOVERY')")
        check("recovery link -> new-password form",await state("session","recovering") and (await txt("#auth-h"))=="Choose a new password" and not await vis("#lbl-email"))
        await pg.fill("#a-pass","newpassword1"); await pg.click("#a-submit")
        check("password set -> ready",await state("session","ready") and await st("role")=="admin")
        await pg.evaluate("__fake.emit('PASSWORD_RECOVERY')"); await state("session","recovering"); await pg.click("#sw-signin")
        check("leaving recovery signs out",await state("session","signedOut") and await st("auth")=="signin")
        await signin("ana@y.z","newpassword1"); await state("session","ready")
        await pg.reload(); check("reload keeps you signed in",await state("session","ready") and await vis("#btn-punch"))
        await pg.evaluate("__fake.emit('TOKEN_REFRESHED'); __fake.emit('SIGNED_IN')"); await settle()
        check("repeat sign-in events are ignored",await st("session")=="ready")
        await pg.click("#btn-lang")
        check("Spanish",(await txt("#btn-punch"))=="Marcar entrada" and await pg.evaluate("document.documentElement.lang")=="es")
        over=await pg.evaluate("document.documentElement.scrollWidth>document.documentElement.clientWidth")
        check("no sideways scroll at phone width",not over)
        check("no console errors or failed self-checks",not errs,errs[:5])
        await b.close()
    print(f"\n{n-len(fails)}/{n} passed"); sys.exit(1 if fails else 0)
asyncio.run(main())
