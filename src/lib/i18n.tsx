export type Lang = "en" | "es";
export type CopyKey = keyof typeof en;

type I18nValue = {
  lang: Lang;
  setLang: (lang: Lang) => void;
  t: (key: CopyKey, vars?: Record<string, string | number>) => string;
};

const I18nContext = createContext<I18nValue | null>(null);

/**
 * English unless this person picked Spanish (ES button or Settings). Only a real
 * choice is saved, under `tc-language`. The old `tc-lang` key also held guesses from
 * the device language, so it is ignored and cleared: everyone starts in English once.
 */
const LANG_KEY = "tc-language";

function readLang(): Lang {
  try {
    localStorage.removeItem("tc-lang");
    return localStorage.getItem(LANG_KEY) === "es" ? "es" : "en";
  } catch {
    return "en";
  }
}

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("en");

  useEffect(() => {
    const next = readLang();
    setLangState(next);
    document.documentElement.lang = next;
  }, []);

  const setLang = useCallback((next: Lang) => {
    setLangState(next);
    document.documentElement.lang = next;
    try {
      localStorage.setItem(LANG_KEY, next);
    } catch {
      /* ignore */
    }
  }, []);

  const t = useCallback(
    (key: CopyKey, vars?: Record<string, string | number>) => {
      let s: string = lang === "es" ? es[key] : en[key];
      if (vars) {
        for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
      }
      return s;
    },
    [lang],
  );

  return <I18nContext.Provider value={{ lang, setLang, t }}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nValue {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("LanguageProvider missing");
  return ctx;
}

